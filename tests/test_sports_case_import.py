"""Sports-source structure checks; require original historical quotations."""
import importlib.util
import hashlib, json, sqlite3, unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SCRIPT=ROOT/'scripts/build_shenqi_16_from_15.py'
source=ROOT/'sources/shenqi/神奇之门_体育竞赛预测_精校完整版(1).txt'

class SportsSourceRegression(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  spec=importlib.util.spec_from_file_location('sports_builder',SCRIPT)
  import sys
  obj=importlib.util.module_from_spec(spec)
  sys.modules[spec.name]=obj
  spec.loader.exec_module(obj)
  cls.module=obj
 def test_whole_source_and_nine_palaces(self):
  m=self.module;raw=source.read_bytes()
  self.assertEqual(len(raw),26814)
  self.assertEqual(hashlib.sha256(raw).hexdigest(),m.SOURCE_HASH)
  lines=raw.decode('utf8').splitlines();self.assertEqual(len(lines),276)
  cases,steps=m.make_indexes(lines)
  self.assertEqual((len(cases),len(steps)),(7,32))
  self.assertEqual([c['printed_chart_start'] for c in cases],[22,61,98,145,178,213,248])
  for c in cases:
   pal=m.chart(lines,c['printed_chart_start'])
   self.assertEqual(len(pal),9)
   self.assertEqual(len([x for x in pal if x[0]==5]),1)
   self.assertTrue(all(x['positive_training_eligible'] is False for x in c['author_source_steps']))
  self.assertEqual(len(m.METHODS),11)
 def test_first_hour_unprinted_and_error_kept(self):
  c,_=self.module.make_indexes(source.read_text(encoding='utf8').splitlines())
  self.assertFalse(c[1]['unprinted_first_cast']['actual_printed_chart'])
  self.assertEqual(c[2]['method_competition']['nine_stars'],[126,128,130,132])
  self.assertEqual(c[4]['score_definition']['90_minute'],'1:1')
  self.assertEqual(c[4]['score_definition']['post_penalty_total_reported'],'5:3')
  self.assertEqual(c[5]['book_outcome'],'author_book_error_explicit')
  self.assertEqual(c[5]['error_and_correction']['first_prediction_line'],235)
  self.assertEqual(c[5]['error_and_correction']['later_result_and_self_correction_line'],237)
  self.assertEqual(self.module.chart(source.read_text(encoding='utf8').splitlines(),178)[1][5],'铺庚')
 def test_published_database_once_ready(self):
  db=ROOT/'archives/sqlite/WenguaApp_神奇之门_16章_84案例_完整研究库.sqlite3'
  manifest=ROOT/'archives/sqlite/16chapters_84cases_manifest.json'
  if not db.exists():self.skipTest('Binary archive is generated by version-specific archive workflow')
  import hashlib
  m=json.loads(manifest.read_text(encoding='utf8'))
  self.assertEqual(hashlib.sha256(db.read_bytes()).hexdigest(),m['sha256'])
  with sqlite3.connect(db) as con:
   self.assertEqual(con.execute('PRAGMA integrity_check').fetchone()[0],'ok')
   self.assertEqual(con.execute('PRAGMA foreign_key_check').fetchall(),[])
   for table,n in [('sections',16),('cases',84),('historical_chart_cells',756),('historical_case_reasoning',376),('semantic_assertions',990),('historical_palace_standardization',801)]:
    self.assertEqual(con.execute('SELECT count(*) FROM '+table).fetchone()[0],n,table)
   self.assertEqual(con.execute('SELECT count(*) FROM historical_sports_cast_qualification').fetchone()[0],2)
   self.assertEqual(con.execute('SELECT count(*) FROM historical_source_literal_anomalies').fetchone()[0],1)
   self.assertEqual(con.execute("SELECT verdict FROM historical_case_book_verdicts WHERE event_family_id='shenqi.sports.case06'").fetchone()[0],'author_book_error_explicit')

if __name__=='__main__':unittest.main()
